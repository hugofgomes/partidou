// Backup da ESTRUTURA do banco de produção (sem dados pessoais) para backup/schema.sql.
// Só leitura: consulta o catálogo do Postgres. Uso: node tools/backup-schema.mjs  (lê DATABASE_URL do .env.deploy)
// Os dados (clientes, reservas, telefones, e-mails) NÃO entram aqui: são dados pessoais (LGPD) e não vão para o GitHub.
import fs from "node:fs"
import pg from "pg"

const env = Object.fromEntries(fs.readFileSync(".env.deploy", "utf8").split("\n").filter((l) => l.includes("=") && !l.startsWith("#")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]))
const c = new pg.Client({ connectionString: process.env.DATABASE_URL || env.DATABASE_URL })
await c.connect()
const q = async (sql) => (await c.query(sql)).rows
const out = []
const sec = (t) => out.push(`\n-- ${"=".repeat(70)}\n-- ${t}\n-- ${"=".repeat(70)}\n`)

const [{ v }] = await q("select current_setting('server_version') v")
out.push(`-- Partigol: estrutura do banco (schema public) exportada em ${new Date().toISOString()}\n-- Postgres ${v}. Sem dados. Para recriar do zero, prefira as migrations em supabase/migrations (este arquivo é o retrato do que está em produção).\n`)

sec("Extensões")
for (const r of await q("select extname, extversion from pg_extension order by 1")) out.push(`-- ${r.extname} ${r.extversion}\ncreate extension if not exists "${r.extname}";`)

sec("Tipos (enum)")
for (const r of await q(`select t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by 1 order by 1`))
  out.push(`create type public.${r.typname} as enum (${r.labels});`)

sec("Sequências")
for (const r of await q(`select sequence_name from information_schema.sequences where sequence_schema = 'public' order by 1`))
  out.push(`create sequence if not exists public.${r.sequence_name};`)

sec("Tabelas")
const tables = await q(`select c.oid, c.relname, c.relrowsecurity rls, c.relforcerowsecurity force from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p') order by 1`)
for (const t of tables) {
  const cols = await q(`select a.attname, format_type(a.atttypid, a.atttypmod) typ, a.attnotnull nn, pg_get_expr(d.adbin, d.adrelid) def, a.attgenerated gen, a.attidentity ident
    from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = ${t.oid} and a.attnum > 0 and not a.attisdropped order by a.attnum`)
  const lines = cols.map((x) => {
    let s = `  "${x.attname}" ${x.typ}`
    if (x.gen === "s") s += ` generated always as (${x.def}) stored`
    else if (x.def) s += ` default ${x.def}`
    if (x.ident) s += x.ident === "a" ? " generated always as identity" : " generated by default as identity"
    if (x.nn) s += " not null"
    return s
  })
  const cons = await q(`select conname, pg_get_constraintdef(oid) def from pg_constraint where conrelid = ${t.oid} and contype in ('p','u','c','x') order by contype, conname`)
  for (const k of cons) lines.push(`  constraint "${k.conname}" ${k.def}`)
  out.push(`create table public."${t.relname}" (\n${lines.join(",\n")}\n);`)
  if (t.rls) out.push(`alter table public."${t.relname}" enable row level security;`)
  if (t.force) out.push(`alter table public."${t.relname}" force row level security;`)
}

sec("Chaves estrangeiras")
for (const r of await q(`select c.conrelid::regclass tbl, c.conname, pg_get_constraintdef(c.oid) def from pg_constraint c join pg_namespace n on n.oid = c.connamespace
  where n.nspname = 'public' and c.contype = 'f' order by 1, 2`))
  out.push(`alter table ${r.tbl} add constraint "${r.conname}" ${r.def};`)

sec("Índices")
for (const r of await q(`select indexdef from pg_indexes i where schemaname = 'public'
  and not exists (select 1 from pg_constraint c where c.conname = i.indexname and c.connamespace = 'public'::regnamespace) order by tablename, indexname`))
  out.push(`${r.indexdef};`)

sec("Views")
for (const r of await q(`select c.relname, c.relkind, pg_get_viewdef(c.oid, true) def from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('v','m') order by 1`))
  out.push(`create ${r.relkind === "m" ? "materialized view" : "or replace view"} public."${r.relname}" as\n${r.def}`)

sec("Funções")
const fns = await q(`select p.oid, p.oid::regprocedure sig, pg_get_functiondef(p.oid) def, p.proacl::text acl from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by 2`)
for (const f of fns) out.push(`${f.def};\n-- permissões: ${f.acl ?? "(padrão)"}\n`)

sec("Gatilhos")
for (const r of await q(`select pg_get_triggerdef(t.oid) def from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal and n.nspname = 'public' order by c.relname, t.tgname`))
  out.push(`${r.def};`)

sec("Políticas de acesso (RLS)")
for (const r of await q(`select tablename, policyname, permissive, roles::text[] roles, cmd, qual, with_check from pg_policies where schemaname = 'public' order by 1, 2`)) {
  let s = `create policy "${r.policyname}" on public."${r.tablename}" as ${r.permissive.toLowerCase()} for ${r.cmd.toLowerCase()} to ${r.roles.join(", ")}`
  if (r.qual) s += `\n  using (${r.qual})`
  if (r.with_check) s += `\n  with check (${r.with_check})`
  out.push(s + ";")
}

sec("Permissões nas tabelas")
for (const r of await q(`select table_name, grantee, string_agg(privilege_type, ', ' order by privilege_type) p from information_schema.role_table_grants
  where table_schema = 'public' and grantee in ('anon','authenticated','service_role') group by 1, 2 order by 1, 2`))
  out.push(`grant ${r.p.toLowerCase()} on public."${r.table_name}" to ${r.grantee};`)

sec("Storage (buckets: só a configuração)")
for (const r of await q(`select id, public, file_size_limit, allowed_mime_types from storage.buckets order by 1`).catch(() => []))
  out.push(`-- bucket ${r.id}: público=${r.public} limite=${r.file_size_limit ?? "-"} tipos=${(r.allowed_mime_types || []).join(",") || "-"}`)

sec("Resumo")
const counts = await q(`select (select count(*) from pg_tables where schemaname='public') tabelas, (select count(*) from pg_policies where schemaname='public') politicas`)
out.push(`-- ${tables.length} tabelas, ${fns.length} funções, ${counts[0].politicas} políticas`)

fs.mkdirSync("backup", { recursive: true })
fs.writeFileSync("backup/schema.sql", out.join("\n") + "\n")
console.log(`backup/schema.sql: ${tables.length} tabelas, ${fns.length} funções, ${counts[0].politicas} políticas`)
await c.end()
